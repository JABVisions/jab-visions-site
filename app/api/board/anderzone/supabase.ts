import { cookies } from "next/headers";
import { createServerClient } from "@supabase/ssr";
import { getSupabasePublicConfig } from "@/lib/supabase/config";

export function anderzoneSupabase() {
  const { url, key, configured } = getSupabasePublicConfig();
  if (!configured) return null;
  const cookieStore = cookies();
  return createServerClient(url, key, {
    cookies: {
      getAll: () => cookieStore.getAll(),
      setAll: (entries) => {
        try {
          entries.forEach(({ name, value, options }) => cookieStore.set(name, value, options));
        } catch {
          // GET handlers may not persist refreshed auth cookies.
        }
      },
    },
  });
}
